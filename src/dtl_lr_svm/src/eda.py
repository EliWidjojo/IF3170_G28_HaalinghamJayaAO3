def EDA (train, test):
    print("=== TRAIN DATASET ===")
    print("\nDataset shape:")
    print(train.shape)
    print("\nFeature types:")
    train.info()
    print("\nMissing values     :")
    print(train.isnull().sum())
    print("\nClass distribution :")
    print(train["loan_status"].value_counts())
    print("\n-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=\n")
    print("=== TEST DATASET ===")
    print("\nDataset shape:")
    print(test.shape)
    print("\nFeature types:")
    test.info()
    print("\nMissing values     :")
    print(test.isnull().sum())
